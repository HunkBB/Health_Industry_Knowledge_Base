def replace_section(path, new_section):
    p = Path(path)
    text = p.read_text(encoding='utf-8')
    start = text.index('## 一、机构公开观点与文献摘要')
    end = text.index('\n## 二、核心问题拆解', start)
    text = text[:start] + new_section.rstrip() + text[end:]
    p.write_text(text, encoding='utf-8')


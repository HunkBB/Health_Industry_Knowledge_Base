def clean_old_blocks(text: str) -> str:
    patterns = [
        (TEMPLATE_START, TEMPLATE_END),
        (OFFICIAL_START, OFFICIAL_END),
        (READING_START, READING_END),
    ]
    for start, end in patterns:
        text = re.sub(re.escape(start) + r'.*?' + re.escape(end) + r'\s*', '', text, flags=re.S)
    text = re.sub(r'(?m)^##\s+正文大纲.*?(?=^##\s+|\Z)', '', text, flags=re.S)
    text = text.replace('链接/备注', '链接/口径').replace('来源/备注', '来源/口径')
    text = re.sub(r'\n{4,}', '\n\n\n', text)
    return text.strip() + '\n'

def extract_title(text: str, fallback: str) -> str:
    m = re.search(r'^#\s+(.+?)\s*$', text, re.M)
    return m.group(1).strip() if m else fallback

def first_bullets(raw: str, limit=4):
    lines=[]
    for line in raw.splitlines():
        s=line.strip()
        if not s or s.startswith('#') or s.startswith('>') or s.startswith('|') or s.startswith('---'):
            continue
        s=re.sub(r'^[-*]\s+', '', s)
        s=re.sub(r'^\d+[.、]\s*', '', s)
        if len(s) < 8:
            continue
        if any(bad in s for bad in ['TYPE_LEARNING_TEMPLATE', 'OFFICIAL_VERIFIED_SUMMARY', 'READING_FRAMEWORK']):
            continue
        lines.append(s[:120])
        if len(lines)>=limit:
            break
    return lines


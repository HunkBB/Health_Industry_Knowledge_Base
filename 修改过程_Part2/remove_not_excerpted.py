from pathlib import Path
root=Path.cwd()

def replace_in(name, repls):
    matches=[p for p in root.rglob('*.md') if name in p.name]
    if not matches:
        print('MISS', name); return
    p=matches[0]
    t=p.read_text(encoding='utf-8')
    old=t
    for a,b in repls:
        t=t.replace(a,b)
    p.write_text(t,encoding='utf-8')
    print('DONE', p.relative_to(root), old.count('未在本文摘录'),'->',t.count('未在本文摘录'))


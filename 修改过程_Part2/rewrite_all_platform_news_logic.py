def title_from(path):
    old = path.read_text(encoding='utf-8', errors='replace')
    m = re.search(r'^#\s+(.+)$', old, re.M)
    return m.group(1).strip() if m else path.stem

def classify(path, title):
    s = str(path.relative_to(PLATFORM)) + title
    if '补贴' in s:
        return 'subsidy'
    if '药店合作' in s:
        return 'pharmacy_coop'
    if any(k in s for k in ['合规', '医保', '处方', '监管']):
        return 'policy'
    if any(k in s for k in ['研报']):
        return 'research'
    if any(k in s for k in ['竞争雷达', '三方对比', '指标表', '入口对比', '来源索引']):
        return 'cross'
    if any(k in s for k in ['京东']):
        return 'jd'
    if any(k in s for k in ['阿里', '淘宝闪购', '饿了么']):
        if any(k in s for k in ['财报', 'FY2026', '业绩', '原文']):
            return 'ali_finance'
        return 'ali_news'
    if any(k in s for k in ['美团']):
        if any(k in s for k in ['财报', 'FY2025', '2026Q1', '业绩']):
            return 'meituan_finance'
        return 'meituan_news'
    return 'cross'


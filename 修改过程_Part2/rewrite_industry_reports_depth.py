def make(title, prof):
    out=[]
    out += [f'# {title}', '', '> - 引用级别：✅可供研判参考', '> - 最后更新：2026-06-18', '']
    out += ['## 一句话定位','']
    out += [f'本文回答：{prof["promise"]}。']
    out += [f'核心判断是：{prof["core"]}。']
    out += ['本文不能证明：单平台GMV、单门店利润、单品动销、用户复购或企业经营结果，除非原始报告、公司公告或监管文件直接披露。','']
    out += ['## 一、先讲清标题里的概念和关系','']
    for k,v in prof['terms']:
        out.append(f'- **{k}**：{v}')
    out += ['', '这一组概念合在一起，实际讨论的是：公开行业资料如何转化为可验证的医药零售判断，而不是把报告摘要直接写成业务结论。','']
    out += ['## 二、事实底座：目前能确定什么','', '| 事实/资料 | 能说明什么 | 不能说明什么 |','|---|---|---|']
    for a,b,c in prof['facts']:
        out.append(f'| {a} | {b} | {c} |')
    out += ['', '这组事实说明：行业报告首先提供的是方向和口径，不是经营结果。要从报告走到业务判断，必须继续解释数据背后的渠道、主体和用户场景。','']
    out += ['## 三、业务机制拆解：为什么会这样','']
    for i,(h,logic,ex) in enumerate(prof['mechanisms'],1):
        out += [f'### {i}. {h}', '', f'- 发生逻辑：{logic}', f'- 具体例子：{ex}', f'- 对判断的影响：这决定了本文只能形成有边界的研判，不能把行业事实直接外推成平台或公司结论。','']
    out += ['## 四、分类讨论：不同对象不能混在一起看','', '| 类型 | 适合回答的问题 | 关键指标 | 风险/限制 |','|---|---|---|---|']
    for a,b,c,d in prof['classes']:
        out.append(f'| {a} | {b} | {c} | {d} |')
    out += ['', '分类讨论的核心是：同一篇行业报告里可能同时出现规模、渠道、政策和企业经营线索，但它们的证据等级不同，不能混成一个结论。','']
    out += ['## 五、需要关注指标/为什么','', '| 需要关注指标 | 为什么 |','|---|---|']
    for a,b in prof['indicators']:
        out.append(f'| {a} | {b} |')
    out.append('')
    return '\n'.join(out)

for title,prof in profiles.items():
    Path(prof['path']).write_text(make(title, prof), encoding='utf-8')

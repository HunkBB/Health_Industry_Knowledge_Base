for title, block in concepts.items():
    rows=indicator_rows[title]
    # find path from title line
    matches=[]
    for p in Path('.').rglob('*.md'):
        if any(part.startswith('backup-') for part in p.parts) or 'tmp' in p.parts:
            continue
        try:
            t=p.read_text(encoding='utf-8')
        except Exception:
            continue
        if t.startswith('# '+title+'\n'):
            matches.append(p)
    if len(matches)!=1:
        raise SystemExit(f'{title} matches {matches}')
    p=matches[0]
    text=p.read_text(encoding='utf-8')
    if '### 0. 先讲清标题里的概念' not in text:
        marker='## 一、本周发生了什么：事件台账'
        text=text.replace(marker, marker+'\n\n'+block, 1)
    start=text.find('## 四、下周需要继续跟踪什么')
    if start==-1:
        raise SystemExit(f'missing section four {p}')
    end=text.find('\n## ', start+1)
    if end!=-1 and text.startswith('\n## 五、本周引用台账', end):
        end2=text.find('\n## ', end+1)
        end = len(text) if end2==-1 else end2
    else:
        end=len(text)
    table=['## 四、需要关注指标/为什么','', '| 需要关注指标 | 为什么 |','|---|---|']
    for a,b in rows:
        table.append(f'| {a} | {b} |')
    text=text[:start]+'\n'.join(table)+'\n'+text[end:]
    p.write_text(text,encoding='utf-8')

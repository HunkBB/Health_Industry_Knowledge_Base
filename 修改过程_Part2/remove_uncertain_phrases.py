from pathlib import Path
root=Path.cwd()

def edit(name, repls, delete_contains=()):
    ms=[p for p in root.rglob('*.md') if name in p.name]
    if not ms: print('MISS',name); return
    p=ms[0]; t=p.read_text(encoding='utf-8'); old=t
    for a,b in repls: t=t.replace(a,b)
    if delete_contains:
        lines=[]
        for line in t.splitlines():
            if any(x in line for x in delete_contains):
                continue
            lines.append(line)
        t='\n'.join(lines)+'\n'
    p.write_text(t,encoding='utf-8')
    print('EDIT',p.relative_to(root),len(old),len(t))

